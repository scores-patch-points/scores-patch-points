#!/usr/bin/env node
// nexus/gen-ci.mjs — EVERY REPO CARRIES THE SAME, SMALL, GENERATED CHECK.
// For each repo whose manifest says ci.workflow = "managed", nexus/ci/<repo>/nexus.yml = the workflow `.github/workflows/nexus.yml`:
//   1. KIT FRESHNESS (when the nexus manages the repo's CLAUDE.md): CLAUDE.md must equal the kit the map generates for this repo today; a hand edit, or a kit
//      that moved on, turns it red. That is the drift catch, in the repo itself, on every push.
//   2. THE GATE, only where the manifest says it has been verified in a clean checkout (ci.gate = true). Elsewhere it is a typed gap with its reason, stated
//      in the run (a notice), never a pass that checked nothing.
// Generated, never edited by hand; `npm test` fails when nexus/ci/ differs from what this generates. Installing is nexus/install-kits.mjs --what ci (owner-approved).
//   node nexus/gen-ci.mjs --write
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { load } from "./gen-map.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const KIT_URL = (name) => `https://raw.githubusercontent.com/scores-patch-points/scores-patch-points/main/nexus/kits/${name}/CLAUDE.md`;

export function ciFor(repo) {
  const steps = [
    "      - uses: actions/checkout@v4",
    "      - uses: actions/setup-node@v4",
    "        with:",
    "          node-version: 22",
  ];
  if (repo.kit === "managed") steps.push(
    "      - name: CLAUDE.md is the generated kit",
    "        run: |",
    `          curl -fsS --retry 3 -o "$RUNNER_TEMP/kit.md" ${KIT_URL(repo.name)}`,
    '          diff -u "$RUNNER_TEMP/kit.md" CLAUDE.md',
  );
  if (repo.kit === "block") steps.push(
    "      - name: the nexus block in CLAUDE.md is the generated block",
    "        run: |",
    `          curl -fsS --retry 3 -o "$RUNNER_TEMP/block.md" ${KIT_URL(repo.name).replace(/kits\/[^/]+\/CLAUDE\.md$/, `blocks/${repo.name}.md`)}`,
    "          sed -n '/<!-- nexus:begin/,/<!-- nexus:end -->/p' CLAUDE.md > \"$RUNNER_TEMP/have.md\"",
    '          diff -u "$RUNNER_TEMP/block.md" "$RUNNER_TEMP/have.md"',
  );
  if (repo.ci.gate && repo.gate?.cmd) steps.push(`      - name: gate (${repo.gate.cmd.replace(/[:#]/g, " ")})`, "        run: |", `          ${repo.gate.cmd}`);
  else steps.push("      - name: gate is a typed gap", "        run: |", `          echo "::notice::gate is a typed gap: ${(repo.ci.gateWhy ?? repo.gate?.why ?? "not verified").replace(/"/g, "'")}. Name one in nexus/nexus.json (scores-patch-points) and regenerate."`);
  return [
    "# Generated by scores-patch-points/scores-patch-points (nexus/gen-ci.mjs) from the nexus manifest. Do not edit by hand:",
    "# change nexus/nexus.json there, regenerate, reinstall. The map's live check fails when this file differs from the generated one.",
    "name: nexus",
    "on:",
    "  push:",
    "  pull_request:",
    "jobs:",
    "  nexus:",
    "    runs-on: ubuntu-latest",
    "    steps:",
    ...steps,
    "",
  ].join("\n");
}

export const ciTargets = (manifest) => manifest.repos.filter((r) => r.ci?.workflow === "managed");

export function generateCi(l = load()) {
  const out = {};
  for (const r of ciTargets(l.manifest)) out[r.name] = ciFor(r);
  return out;
}

export function readCi() {
  const dir = path.join(HERE, "ci"), out = {};
  if (!fs.existsSync(dir)) return out;
  for (const n of fs.readdirSync(dir)) { const f = path.join(dir, n, "nexus.yml"); if (fs.existsSync(f)) out[n] = fs.readFileSync(f, "utf8"); }
  return out;
}

if (process.argv[1] && import.meta.url === new URL(`file://${path.resolve(process.argv[1])}`).href && process.argv.includes("--write")) {
  const ci = generateCi();
  for (const [n, t] of Object.entries(ci)) { fs.mkdirSync(path.join(HERE, "ci", n), { recursive: true }); fs.writeFileSync(path.join(HERE, "ci", n, "nexus.yml"), t); }
  console.log(`gen-ci: wrote ${Object.keys(ci).length} workflows: ${Object.keys(ci).join(", ")}`);
}
